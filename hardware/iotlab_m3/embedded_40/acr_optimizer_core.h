/*
 * Portable C99 deterministic inner kernel of the frozen acr_mcr_v2.py:
 * Floyd-Warshall head backbone, member assignment, full fitness including
 * empirical CVaR, survivor selection with external NumPy RNG trace.
 *
 * NOT a port of NumPy PCG64 / SeedSequence RNG, predictor-state update,
 * or a deployed closed-loop physical ACR-MCR controller.
 * Stress tensors are supplied through a callback: no 64x40x41 double tensor
 * needs to reside in MCU RAM.
 */
#ifndef ACR_OPTIMIZER_CORE_H
#define ACR_OPTIMIZER_CORE_H
#include <stdint.h>
#define ACR_N 40
#define ACR_LINKS (ACR_N+1)
#define ACR_MAX_HEADS 8
#define ACR_MAX_PATH (ACR_MAX_HEADS+2)
#define ACR_TAIL_MAX 64
#define ACR_POP 8
#define ACR_GENERATIONS 4
#define ACR_CHILDREN 6
#define ACR_CANDIDATES (ACR_POP+ACR_GENERATIONS*ACR_CHILDREN)
typedef void (*acr_stress_cb)(void *ptr,unsigned scenario,unsigned u,
                               unsigned v,double *cost,double *delay);
typedef struct {
  int n;
  int stress_samples;
  int has_risk;
  int load;
  double deadline_ms,tail_weight,tail_beta;
  uint8_t active[ACR_N];
  const double *edge_cost;     /* row-major [n][n+1] */
  const double *attempt_mean;
  const double *tx_energy;
  const double *distance;
  const double *d_used;
  const double *energy;        /* n */
  acr_stress_cb stress;
  void *stress_user;
} ACR_OptContext;
typedef struct {
  int nheads;
  int heads[ACR_MAX_HEADS];
  int assigned[ACR_N];
  double costs[ACR_N];
  int path_len[ACR_MAX_HEADS];
  int paths[ACR_MAX_HEADS][ACR_MAX_PATH];
  double objective;
} ACR_OptPlan;
typedef struct {
  /* 8 initial candidate head sets, then 6 children in each generation.
     All genotypes are generated by the *original* NumPy RNG in Python. */
  int nheads;
  int heads[ACR_CANDIDATES][ACR_MAX_HEADS];
} ACR_SearchTrace;
int acr_make_plan(const ACR_OptContext *s,const int *heads,int k,
                  ACR_OptPlan *plan);
double acr_fitness(const ACR_OptContext *s,ACR_OptPlan *p);
int acr_select_trace(const ACR_OptContext *s,const ACR_SearchTrace *trace,
                     ACR_OptPlan *best);
#endif
